import type { FieldHook } from 'payload'
import type { User } from '@/payload-types'

/**
 * beforeChange-хук на поле `roles` коллекции Users.
 * Вызывается при каждом создании/обновлении пользователя — как через
 * публичную регистрацию, так и через админ-панель или Local API.
 */
export const protectRoles: FieldHook<User> = async ({ req, data }) => {
  // ---------------------------------------------------------------
  // Случай 1: req.user отсутствует.
  // Это значит, что запрос пришёл БЕЗ авторизации — то есть либо это
  // анонимная саморегистрация нового посетителя сайта, либо вызов
  // через Local API (сид-скрипт / миграция, которая тоже не аутентифицирована).
  // ---------------------------------------------------------------
  if (!req.user) {
    // Считаем, сколько пользователей уже есть в системе.
    const { totalDocs } = await req.payload.count({ collection: 'users' })

    // Если это самый первый пользователь — выдаём ему admin.
    // Так решается классическая проблема "как завести первого админа",
    // не отключая хук вручную и не лазая в БД напрямую.
    if (totalDocs === 0) {
      return ['admin', 'user']
    }

    // Все последующие саморегистрации — обычные пользователи.
    // Это критично: без этой ветки злоумышленник мог бы прислать
    // { roles: ['admin'] } в теле запроса на регистрацию и получить админку.
    return ['user']
  }

  // ---------------------------------------------------------------
  // Случай 2: запрос от авторизованного пользователя (например,
  // редактирование чужого профиля через админ-панель).
  // ---------------------------------------------------------------
  const isAdmin = req.user.roles?.includes('admin')

  // Не-админ не может назначить ни себе, ни кому-либо другому
  // повышенные роли — что бы ни пришло в data.roles, откатываем до 'user'.
  if (!isAdmin) {
    return ['user']
  }

  // Админ может назначать любые роли. 'user' добавляем принудительно,
  // чтобы базовые права (свой профиль, избранное) были всегда,
  // даже если админ случайно снял чекбокс 'user' в форме.
  const roles = new Set(data?.roles ?? [])
  roles.add('user')
  return [...roles]
}

